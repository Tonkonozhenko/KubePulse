//! Workspace, tabs, table, editor, terminal, and the declarative UI renderer.
//!
//! This is the only crate that uses the UI toolkit.

use gpui_kit::*;

struct Hello;

impl Render for Hello {
    fn render(&mut self, _: &mut Window, _: &mut Context<Self>) -> impl IntoElement {
        div()
            .size_full()
            .flex()
            .items_center()
            .justify_center()
            .child("Hello, World!")
    }
}

/// Opens the main window and runs the application until it exits.
pub fn run() {
    gpui_kit::application().run(|cx| {
        gpui_kit::init(cx);
        gpui_kit::open_window(WindowOptions::default(), cx, |_, cx| cx.new(|_| Hello))
            .expect("failed to open window");
    });
}
