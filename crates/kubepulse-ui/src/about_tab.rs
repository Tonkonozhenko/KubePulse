//! The application's license and the notices its dependencies require, in a tab
//! that belongs to no cluster.

use std::{ops::Range, sync::LazyLock};

use gpui_kit::{
    assets::IconName,
    component::{
        ActiveTheme as _, Icon, Selectable as _, Sizable as _,
        button::Button,
        dock::{self, PanelEvent},
        scroll::{Scrollbar, ScrollbarMode},
    },
    *,
};
use rust_i18n::t;

use crate::shell_state::{SharedShellState, ShellState, close_button, close_on_middle_click};

pub const PANEL_NAME: &str = "AboutTab";
pub const LICENSE: &str = include_str!("../../../LICENSE");
/// Generated by `cargo about`, as described in `about.toml`.
pub const NOTICES: &str = include_str!("../../../assets/third-party-notices.txt");

gpui_kit::actions!(kubepulse, [OpenAbout]);

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Document {
    License,
    Notices,
}

struct Lines {
    lines: Vec<&'static str>,
    widest: usize,
}

impl Lines {
    fn of(text: &'static str) -> Self {
        let lines: Vec<&str> = text.lines().collect();
        let widest = (0..lines.len())
            .max_by_key(|&index| lines[index].chars().count())
            .unwrap_or(0);
        Self { lines, widest }
    }
}

static LICENSE_LINES: LazyLock<Lines> = LazyLock::new(|| Lines::of(LICENSE));
static NOTICE_LINES: LazyLock<Lines> = LazyLock::new(|| Lines::of(NOTICES));

impl Document {
    fn lines(self) -> &'static Lines {
        match self {
            Document::License => &LICENSE_LINES,
            Document::Notices => &NOTICE_LINES,
        }
    }
}

pub struct AboutTab {
    shown: Document,
    shell: Entity<ShellState>,
    focus: FocusHandle,
    list: UniformListScrollHandle,
}

impl AboutTab {
    pub fn new(cx: &mut Context<Self>) -> Self {
        Self {
            shown: Document::License,
            shell: cx.global::<SharedShellState>().0.clone(),
            focus: cx.focus_handle(),
            list: UniformListScrollHandle::new(),
        }
    }

    pub fn shown(&self) -> Document {
        self.shown
    }

    fn show(&mut self, document: Document, cx: &mut Context<Self>) {
        self.shown = document;
        self.list = UniformListScrollHandle::new();
        cx.notify();
    }

    fn document_button(
        &self,
        id: &'static str,
        label: String,
        document: Document,
        cx: &mut Context<Self>,
    ) -> Button {
        Button::new(id)
            .label(label)
            .small()
            .selected(self.shown == document)
            .on_click(cx.listener(move |this, _, _, cx| this.show(document, cx)))
    }

    fn render_lines(&self, cx: &mut Context<Self>) -> impl IntoElement + use<> {
        let lines = self.shown.lines();
        // The list measures its rows outside its own text style, so the style
        // goes on a parent.
        div()
            .id("about-text")
            .flex_1()
            .min_h_0()
            .w_full()
            .flex()
            .flex_col()
            .font_family(cx.theme().mono_font_family.clone())
            .text_sm()
            .child(
                div()
                    .flex_1()
                    .min_h_0()
                    .flex()
                    .child(
                        uniform_list(
                            "about-lines",
                            lines.lines.len(),
                            move |range: Range<usize>, _, _| {
                                lines.lines[range]
                                    .iter()
                                    .map(|line| div().whitespace_nowrap().child(*line))
                                    .collect()
                            },
                        )
                        .with_horizontal_sizing_behavior(
                            ListHorizontalSizingBehavior::Unconstrained,
                        )
                        .with_width_from_item(Some(lines.widest))
                        .track_scroll(&self.list)
                        .flex_1()
                        .min_w_0()
                        .h_full(),
                    )
                    .child(
                        div()
                            .relative()
                            .flex_none()
                            .h_full()
                            .w(Scrollbar::width())
                            .child(
                                Scrollbar::vertical(&self.list)
                                    .viewport_from_layout()
                                    .mode(ScrollbarMode::Always),
                            ),
                    ),
            )
            .child(
                div()
                    .relative()
                    .flex_none()
                    .mr(Scrollbar::width())
                    .h(Scrollbar::width())
                    .child(
                        Scrollbar::horizontal(&self.list)
                            .viewport_from_layout()
                            .mode(ScrollbarMode::Always),
                    ),
            )
            .test_support()
    }
}

impl gpui_kit::base::dock::Panel for AboutTab {
    fn panel_name(&self) -> &'static str {
        PANEL_NAME
    }

    fn zoomable(&self, _: &App) -> bool {
        false
    }

    fn closable(&self, _: &App) -> bool {
        false
    }

    fn on_added_to(
        &mut self,
        _: WeakEntity<gpui_kit::base::dock::TabGroup>,
        _: &mut Window,
        cx: &mut Context<Self>,
    ) {
        let tab = cx.weak_entity();
        self.shell
            .update(cx, |shell, _| shell.set_about_tab(Some(tab)));
    }

    fn on_removed(&mut self, _: &mut Window, cx: &mut Context<Self>) {
        self.shell.update(cx, |shell, _| shell.set_about_tab(None));
    }
}

impl dock::Panel for AboutTab {
    fn title(&mut self, _: &mut Window, cx: &mut Context<Self>) -> impl IntoElement {
        div()
            .id("about-tab-title")
            .flex()
            .items_center()
            .gap_2()
            .child(Icon::new(IconName::Info).xsmall())
            .child(t!("about.title").to_string())
            .on_aux_click(close_on_middle_click(cx.entity_id(), self.shell.clone()))
            .child(close_button(cx.entity_id(), self.shell.clone()))
            .test_support()
    }
}

impl EventEmitter<PanelEvent> for AboutTab {}

impl Focusable for AboutTab {
    fn focus_handle(&self, _: &App) -> FocusHandle {
        self.focus.clone()
    }
}

impl Render for AboutTab {
    fn render(&mut self, _: &mut Window, cx: &mut Context<Self>) -> impl IntoElement {
        div()
            .id("about")
            .size_full()
            .p_3()
            .flex()
            .flex_col()
            .gap_2()
            .track_focus(&self.focus)
            .child(
                div()
                    .text_lg()
                    .child(t!("about.heading", version = env!("CARGO_PKG_VERSION")).to_string()),
            )
            .child(
                div()
                    .text_color(cx.theme().muted_foreground)
                    .child(t!("about.summary").to_string()),
            )
            .child(
                div()
                    .flex()
                    .gap_1()
                    .child(self.document_button(
                        "about-license",
                        t!("about.license").to_string(),
                        Document::License,
                        cx,
                    ))
                    .child(self.document_button(
                        "about-notices",
                        t!("about.notices").to_string(),
                        Document::Notices,
                        cx,
                    )),
            )
            .child(self.render_lines(cx))
            .test_support()
    }
}
